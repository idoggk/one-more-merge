// Writes unity/parity/cases.json: the TS core's answers that the C# port (unity/OneMoreMerge.Core) must reproduce exactly.
// Usage: npx vite-node tools/export-parity-cases.ts      (see unity/README.md)
// Reads src/ and tests/golden (never edits them); only writes unity/parity/cases.json.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { LEVELS } from '../src/content/levels';
import { COLS, MAX_RANK, ROWS } from '../src/content/tuning';
import { newLevel } from '../src/core/game';
import { Rng } from '../src/core/rng';
import { writeBoardCases } from './export-parity-board';

const STEPS = 32;
const RNG_SEEDS = [0, 1, 42, 150001, 0x6d2b79f5, 0x7fffffff, 0x80000000, 0xffffffff];
const INT_BOUNDS = [2, 5, 30, 1000];

/** FNV-1a over the UTF-16 code units of ASCII text (same as roster4.stateHash), shown as hex8:length. */
const hashText = (text: string): string => {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return `${h.toString(16).padStart(8, '0')}:${text.length}`;
};

const rngCases = RNG_SEEDS.map((seed) => {
  const r = new Rng(seed);
  const next = Array.from({ length: STEPS }, () => r.next());
  const stateAfter = r.state;
  const ints = INT_BOUNDS.map((n) => ({ n, values: (() => { const q = new Rng(seed); return Array.from({ length: STEPS }, () => q.int(n)); })() }));
  const shuffled = new Rng(seed).shuffle(Array.from({ length: 12 }, (_, i) => i));
  return { seed, steps: STEPS, next, stateAfter, ints, shuffle12: shuffled };
});

// Level-init cases: ordinary + teaching levels whose start board is plain (no modifier, boss, mini-boss, extra pieces or shooter override; stage/goal HP is not ported yet, so hp= is the level file value).
const plain = (d: (typeof LEVELS)[number]) => d.modifier === 'NONE' && (d.level % 10 !== 0 || !!d.teach) && !d.mini_boss && !d.start_extra && !d.shooter;
const levelCases = LEVELS.filter(plain).map((d) => {
  const s = newLevel(d);
  const grid = s.grid.map((g) => (g ? `${g.family}:${g.rank}` : '-')).join(',');
  const text = `L${s.level};hp=${d.hp};time=${s.levelTime};copyCap=${s.copyCap};rankCap=${s.rankCap};target=${s.target};grid=${grid}`;
  return { level: d.level, seed: d.seed, text, hash: hashText(text) };
});

const golden = JSON.parse(readFileSync(new URL('../tests/golden/flagsOff.json', import.meta.url), 'utf8')) as Record<string, string>;
const out = {
  schema: 1,
  note: 'generated by tools/export-parity-cases.ts; do not edit by hand',
  constants: { rows: ROWS, cols: COLS, maxRank: MAX_RANK },
  rng: rngCases,
  levelInit: levelCases,
  // First source for later phases (full-play parity): the flags-off golden trails, copied verbatim. Not asserted in step 1.
  goldenFlagsOff: golden,
};
mkdirSync(new URL('../unity/parity/', import.meta.url), { recursive: true });
writeFileSync(new URL('../unity/parity/cases.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
console.log(`wrote unity/parity/cases.json: ${rngCases.length} rng seeds, ${levelCases.length} level-init cases, ${Object.keys(golden).length} golden entries`);
writeBoardCases(); // step 2: unity/parity/cases2.json
